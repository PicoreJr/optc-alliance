let lang = 'fr';
try {
  const saved = localStorage.getItem('optc.lang');
  if (saved === 'fr' || saved === 'en') lang = saved;
  else if (!(navigator.language || '').toLowerCase().startsWith('fr')) lang = 'en';
} catch (e) { /* stockage indisponible */ }

export function getLang() { return lang; }

export function setLang(l) {
  lang = l;
  try { localStorage.setItem('optc.lang', l); } catch (e) { /* ignore */ }
  document.documentElement.lang = l;
}

export function t(key, vars) {
  let s = (DICT[lang] && DICT[lang][key]) ?? DICT.fr[key] ?? key;
  if (vars) for (const k in vars) s = s.replaceAll('{' + k + '}', vars[k]);
  return s;
}

export function fmtNumber(n) {
  if (n === null || n === undefined || n === '') return '—';
  return Number(n).toLocaleString(lang === 'fr' ? 'fr-FR' : 'en-US');
}

export function fmtDate(iso) {
  if (!iso) return '';
  const d = new Date(iso);
  return d.toLocaleDateString(lang === 'fr' ? 'fr-FR' : 'en-US', { day: 'numeric', month: 'short', year: 'numeric' });
}
